#!/usr/bin/env node
/**
 * Regenerates `src/lib/utils/html-sanitizer/clobber-names.generated.ts`.
 *
 * The HTML sanitizer drops an `id` or `name` attribute whose value would
 * shadow a built-in property of `document` or of a `<form>` element
 * (DOM clobbering — e.g. `<img name="cookie">` makes `document.cookie` an
 * element). DOMPurify performs the same check at runtime (`SANITIZE_DOM`:
 * `value in document || value in formElement`), but the sanitizer here also
 * runs on the server, where there is no `document`, and must produce
 * byte-identical output on both sides so `{@html}` hydrates cleanly. So the
 * set is captured once, from a real browser and from jsdom, and committed.
 *
 * Usage (from frontend/):
 *   node scripts/generate-clobber-names.js [path-to-chromium]
 *
 * The Chromium path defaults to Playwright's own download; pass an explicit
 * executable when the environment provides one (e.g. /opt/pw-browsers/chromium).
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { JSDOM } from 'jsdom';

const OUTPUT = fileURLToPath(
	new URL('../src/lib/utils/html-sanitizer/clobber-names.generated.ts', import.meta.url)
);

/** Evaluated in the page: every name for which `name in target` is true. */
const COLLECT = `(() => {
	const names = new Set();
	const walk = (o) => {
		for (; o; o = Object.getPrototypeOf(o)) {
			for (const n of Object.getOwnPropertyNames(o)) names.add(n);
		}
	};
	walk(document);
	walk(document.createElement('form'));
	return [...names];
})()`;

const executablePath = process.argv[2];
const browser = await chromium.launch(executablePath ? { executablePath } : {});
let chromiumNames;
let chromiumVersion;
try {
	const page = await browser.newPage();
	await page.setContent('<!doctype html><html><head></head><body></body></html>');
	chromiumNames = await page.evaluate(COLLECT);
	chromiumVersion = browser.version();
} finally {
	await browser.close();
}

const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>', {
	runScripts: 'outside-only'
});
const jsdomNames = dom.window.eval(COLLECT);
const jsdomVersion = (await import('jsdom/package.json', { with: { type: 'json' } })).default
	.version;

const names = [...new Set([...chromiumNames, ...jsdomNames])].sort();

const source = `/**
 * GENERATED by scripts/generate-clobber-names.js — do not edit by hand.
 *
 * Property names reachable through \`name in document\` or
 * \`name in document.createElement('form')\` in Chromium ${chromiumVersion} and
 * jsdom ${jsdomVersion} (${names.length} names). An \`id\`/\`name\` attribute with one
 * of these values is dropped by the HTML sanitizer to prevent DOM clobbering.
 */
export const CLOBBER_NAMES: ReadonlySet<string> = new Set([
${names.map((name) => `\t'${name}'`).join(',\n')}
]);
`;

writeFileSync(OUTPUT, source);
console.log(`wrote ${names.length} names to ${OUTPUT}`);
